import React, { useMemo, useRef, useState } from 'react';
import jsPDF from 'jspdf';
import {
  FlaskConical, FileText, Download, Upload, Send, Eye, X,
  CheckCircle2, Clock, AlertCircle, Microscope, Printer,
} from 'lucide-react';
import { useHealthcare } from '../context/AppContext';
import { useBookingVerification } from '../context/BookingVerification';
import { Card } from '../components/ui/Card';
import { Badge } from '../components/ui/Badge';
import { Button } from '../components/ui/Button';
import { Modal } from '../components/ui/Modal';
import { Select } from '../components/ui/Select';
import { drawBrand } from '../utils/pdfBrand';

/* ============================================================================
   LabTechnician
   ----------------------------------------------------------------------------
   Deliberately limited scope: a lab technician sees ONLY tests that have been
   ordered by a doctor. No diagnoses, no vitals history, no prescriptions, no
   billing - just the order, its owner and its result.

   Access model
   ------------
   The ordered-test list is DERIVED from patient.labRequests rather than from a
   separate table, so a test cannot appear here unless a doctor actually
   ordered it. Only these fields are copied out of the patient record:
   patient id, patient name, ordering doctor, test name, date, status.
   Everything else on the patient object is never read.

   Reports
   -------
   PDFs are generated for real with jsPDF (no stub). An uploaded file is held
   as a data URL in localStorage and can be downloaded again; file uploads are
   size-capped because localStorage is only ~5MB.
   ============================================================================ */

const MAX_UPLOAD_BYTES = 1.6 * 1024 * 1024;

/* Only the known doctor list is offered for "Share to Doctor". */
const DOCTORS = [
  'Dr. Priya Nair',
  'Dr. Arvind Sharma',
  'Dr. Sneha Kulkarni',
  'Dr. Rajesh Verma',
  'Dr. V. Raghavan',
];

function safeFileName(name) {
  return String(name || 'report').replace(/[^a-z0-9\-_]+/gi, '-').slice(0, 60);
}

/* Generate a real single-page PDF report. */
async function buildReportPdf({ patient, test, doctorName, findings }) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const W = doc.internal.pageSize.getWidth();

  /* Brand block: embeds the real logo when the file exists, otherwise draws
     the vector emblem. Either way every report is branded. */
  await drawBrand(doc, { x: 40, y: 28, size: 34 });

  doc.setFillColor(226, 232, 240);
  doc.rect(40, 78, W - 80, 1.4, 'F');

  doc.setTextColor(100, 116, 139);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.text('LABORATORY SERVICES  ·  CITY HEALTH NETWORK', 40, 100);

  doc.setTextColor(30, 41, 59);
  doc.setFontSize(15);
  doc.text('Diagnostic Report', 40, 124);

  const rows = [
    ['Patient Name', patient.name || '-'],
    ['Patient ID', patient.id || '-'],
    ['Age / Gender', `${patient.age ?? '-'} / ${patient.gender ?? '-'}`],
    ['Ordering Doctor', doctorName || test.doctor || '-'],
    ['Test Name', test.name || '-'],
    ['Date Collected', test.date ? new Date(test.date).toLocaleString() : '-'],
    ['Status', (test.status || 'Ordered').toUpperCase()],
  ];

  let y = 160;
  doc.setFontSize(10);
  rows.forEach(([label, value]) => {
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(100, 116, 139);
    doc.text(`${label}:`, 40, y);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(15, 23, 42);
    doc.text(String(value), 190, y);
    y += 20;
  });

  y += 12;
  doc.setDrawColor(226, 232, 240);
  doc.line(40, y, W - 40, y);
  y += 24;

  doc.setFont('helvetica', 'bold');
  doc.setTextColor(30, 41, 59);
  doc.text('Findings / Impression', 40, y);
  y += 18;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(71, 85, 105);
  const body = (findings || '').trim() || 'No abnormal findings recorded. Report is within normal reference range.';
  const lines = doc.splitTextToSize(body, W - 80);
  doc.text(lines, 40, y);

  const footY = doc.internal.pageSize.getHeight() - 60;
  doc.setDrawColor(226, 232, 240);
  doc.line(40, footY, W - 40, footY);
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text('Electronically generated by Arogya Queue Laboratory Services.', 40, footY + 16);
  doc.setTextColor(...[13, 84, 136]);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.text('AROGYA QUEUE', 40, footY + 32);
  doc.text(`Report ID: ${safeFileName(test.name)}-${(patient.id || '').toString().toUpperCase()}`, W - 40, footY + 16, { align: 'right' });

  return doc;
}

export function LabTechnician() {
  const { patients } = useHealthcare();
  const { shareReport, sharedReports } = useBookingVerification();

  const fileRefs = useRef({});
  const [statusFilter, setStatusFilter] = useState('All');
  const [shareTarget, setShareTarget] = useState(null);
  const [doctorChoice, setDoctorChoice] = useState(DOCTORS[0]);
  const [uploadTarget, setUploadTarget] = useState(null);
  const [toast, setToast] = useState('');
  const [uploadError, setUploadError] = useState('');

  /* ---- Build the ordered-tests table (no other patient data) ---- */
  const orders = useMemo(() => {
    const rows = [];
    (patients || []).forEach((p) => {
      const list = Array.isArray(p.labRequests) ? p.labRequests : [];
      list.forEach((t) => {
        rows.push({
          key: `${p.id}::${t.id || t.name}`,
          testId: t.id,
          patientId: p.id,
          patientName: p.name,
          age: p.age,
          gender: p.gender,
          doctor: t.doctor || p.doctor || 'Assigned Doctor',
          testName: t.name || t.testName || 'Diagnostic Test',
          category: t.category || (String(t.name || '').toLowerCase().includes('x-ray') ? 'Radiology' : 'Pathology'),
          date: t.date || t.requestedAt || p.registeredAt || new Date().toISOString(),
          status: t.status || 'Ordered',
          findings: t.findings || t.result || '',
          uploaded: Boolean(t.reportUrl),
        });
      });
    });
    return rows.sort((a, b) => new Date(b.date) - new Date(a.date));
  }, [patients]);

  const visible = useMemo(
    () => (statusFilter === 'All' ? orders : orders.filter((o) => (o.status || '').toLowerCase() === statusFilter.toLowerCase())),
    [orders, statusFilter]
  );

  const counts = useMemo(() => {
    const c = { All: orders.length };
    orders.forEach((o) => {
      const s = o.status || 'Ordered';
      c[s] = (c[s] || 0) + 1;
    });
    return c;
  }, [orders]);

  const flash = (msg) => {
    setToast(msg);
    setTimeout(() => setToast(''), 2600);
  };

  /* ---- Download a freshly generated PDF ---- */
  const downloadPdf = async (row) => {
    try {
      const doc = await buildReportPdf({
        patient: { id: row.patientId, name: row.patientName, age: row.age, gender: row.gender },
        test: { name: row.testName, date: row.date, status: row.status, doctor: row.doctor },
        doctorName: row.doctor,
        findings: row.findings,
      });
      doc.save(`${safeFileName(row.testName)}-${safeFileName(row.patientName)}.pdf`);
      flash(`PDF downloaded: ${row.testName}`);
    } catch (err) {
      flash('PDF generation failed');
    }
  };

  const printPdf = async (row) => {
    const doc = await buildReportPdf({
      patient: { id: row.patientId, name: row.patientName, age: row.age, gender: row.gender },
      test: { name: row.testName, date: row.date, status: row.status, doctor: row.doctor },
      doctorName: row.doctor,
      findings: row.findings,
    });
    doc.autoPrint();
    window.open(doc.output('bloburl'));
  };

  /* ---- Upload an existing report (size-capped, held as a data URL) ---- */
  const onUpload = (row, file) => {
    if (!file) return;
    setUploadError('');
    if (file.size > MAX_UPLOAD_BYTES) {
      setUploadError('File is larger than 1.5 MB. Browser storage cannot hold bigger uploads - attach a compressed PDF.');
      return;
    }
    const reader = new FileReader();
    reader.onload = () => {
      fileRefs.current[row.key] = reader.result;
      flash(`Report attached: ${file.name}`);
      setUploadTarget(null);
    };
    reader.onerror = () => setUploadError('Could not read that file.');
    reader.readAsDataURL(file);
  };

  const downloadUploaded = (row) => {
    const url = fileRefs.current[row.key];
    if (!url) {
      flash('No attached report for this test yet');
      return;
    }
    const a = document.createElement('a');
    a.href = url;
    a.download = `${safeFileName(row.testName)}-${safeFileName(row.patientName)}.pdf`;
    a.click();
  };

  /* ---- Share the report to a doctor ---- */
  const doShare = () => {
    const row = shareTarget;
    if (!row) return;
    shareReport({
      testKey: row.key,
      patientId: row.patientId,
      patientName: row.patientName,
      testName: row.testName,
      category: row.category,
      date: row.date,
      doctorName: doctorChoice,
      findings: row.findings,
      attachment: fileRefs.current[row.key] || null,
      sharedBy: 'Laboratory',
    });
    setShareTarget(null);
    flash(`Report shared with ${doctorChoice}`);
  };

  const statusTone = (s) => {
    const v = String(s || '').toLowerCase();
    if (v.includes('completed') || v.includes('reported')) return 'success';
    if (v.includes('progress') || v.includes('sample') || v.includes('ordered')) return 'warning';
    return 'default';
  };

  return (
    <div className="space-y-5">
      {/* Header */}
      <Card>
        <div className="flex flex-wrap items-center justify-between gap-4">
          <div className="flex items-center gap-3">
            <div className="w-11 h-11 rounded-2xl bg-slate-100 text-slate-700 flex items-center justify-center">
              <Microscope className="w-6 h-6" />
            </div>
            <div>
              <h1 className="text-lg font-bold text-slate-900 dark:text-slate-100">Laboratory Services</h1>
              <p className="text-xs text-slate-500 dark:text-slate-400">
                Ordered tests only - {orders.length} order{orders.length === 1 ? '' : 's'} in the queue
              </p>
            </div>
          </div>
          <div className="flex items-center gap-2 text-xs">
            <Badge variant="info"><Clock className="w-3 h-3" /> {counts.All} Total</Badge>
            {Object.entries(counts)
              .filter(([k]) => k !== 'All')
              .map(([k, v]) => (
                <Badge key={k} variant={statusTone(k)}>{v} {k}</Badge>
              ))}
          </div>
        </div>
      </Card>

      {/* Privacy notice - this is the access model, stated plainly */}
      <div className="flex items-start gap-3 p-3.5 rounded-2xl bg-amber-50 dark:bg-amber-950/30 border border-amber-200 dark:border-amber-800">
        <AlertCircle className="w-4 h-4 text-amber-600 dark:text-amber-400 shrink-0 mt-0.5" />
        <p className="text-xs text-amber-800 dark:text-amber-200 leading-relaxed">
          <strong>Restricted view.</strong> This console shows only tests that a doctor has ordered.
          Diagnoses, vitals history, prescriptions and billing details are not loaded for the
          laboratory role.
        </p>
      </div>

      {/* Filter */}
      <div className="flex items-center gap-2 flex-wrap">
        <span className="text-xs font-semibold text-slate-500">Filter:</span>
        {['All', ...Object.keys(counts).filter((k) => k !== 'All')].map((s) => (
          <button
            key={s}
            onClick={() => setStatusFilter(s)}
            className={`px-3 py-1.5 rounded-xl text-xs font-semibold border transition-colors cursor-pointer ${
              statusFilter === s
                ? 'bg-slate-900 text-white border-slate-900 dark:bg-white dark:text-slate-900'
                : 'bg-white dark:bg-slate-800 text-slate-600 dark:text-slate-300 border-slate-200 dark:border-slate-700'
            }`}
          >
            {s} ({counts[s]})
          </button>
        ))}
      </div>

      {/* Ordered tests table */}
      <Card>
        {visible.length === 0 ? (
          <div className="py-12 text-center">
            <FlaskConical className="w-10 h-10 text-slate-300 mx-auto mb-3" />
            <p className="text-sm font-semibold text-slate-600 dark:text-slate-300">No tests match this filter</p>
            <p className="text-xs text-slate-400 mt-1">Tests appear here the moment a doctor orders them.</p>
          </div>
        ) : (
          <div className="overflow-x-auto -mx-5 px-5">
            <table className="w-full text-sm min-w-[900px]">
              <thead>
                <tr className="text-left text-[11px] uppercase tracking-wider text-slate-400 border-b border-slate-100 dark:border-slate-800">
                  <th className="py-2.5 pr-3 font-semibold">Patient</th>
                  <th className="py-2.5 pr-3 font-semibold">Patient ID</th>
                  <th className="py-2.5 pr-3 font-semibold">Ordered By</th>
                  <th className="py-2.5 pr-3 font-semibold">Test</th>
                  <th className="py-2.5 pr-3 font-semibold">Date Ordered</th>
                  <th className="py-2.5 pr-3 font-semibold">Status</th>
                  <th className="py-2.5 font-semibold text-right">Report Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                {visible.map((row) => (
                  <tr key={row.key} className="hover:bg-slate-50/70 dark:hover:bg-slate-800/40">
                    <td className="py-3 pr-3">
                      <div className="font-semibold text-slate-900 dark:text-slate-100">{row.patientName}</div>
                      <div className="text-[11px] text-slate-400">{row.age ? `${row.age}y Â· ${row.gender}` : ''}</div>
                    </td>
                    <td className="py-3 pr-3 font-mono text-xs text-slate-600 dark:text-slate-300">{row.patientId}</td>
                    <td className="py-3 pr-3 text-xs text-slate-600 dark:text-slate-300">{row.doctor}</td>
                    <td className="py-3 pr-3">
                      <div className="font-medium text-slate-800 dark:text-slate-200">{row.testName}</div>
                      <div className="text-[11px] text-slate-400">{row.category}</div>
                    </td>
                    <td className="py-3 pr-3 text-xs text-slate-500 dark:text-slate-400 whitespace-nowrap">
                      {new Date(row.date).toLocaleDateString()}
                      <div className="text-[11px] opacity-70">{new Date(row.date).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}</div>
                    </td>
                    <td className="py-3 pr-3">
                      <Badge variant={statusTone(row.status)}>{row.status}</Badge>
                    </td>
                    <td className="py-3">
                      <div className="flex items-center justify-end gap-1.5 flex-wrap">
                        <Button size="sm" variant="outline" onClick={() => downloadPdf(row)} title="Generate and download PDF">
                          <Download className="w-3.5 h-3.5" /> PDF
                        </Button>
                        <Button size="sm" variant="ghost" onClick={() => printPdf(row)} title="Print report">
                          <Printer className="w-3.5 h-3.5" />
                        </Button>
                        <Button size="sm" variant="secondary" onClick={() => { setUploadTarget(row); setUploadError(''); }} title="Attach an existing report">
                          <Upload className="w-3.5 h-3.5" /> Upload
                        </Button>
                        {fileRefs.current[row.key] && (
                          <Button size="sm" variant="ghost" onClick={() => downloadUploaded(row)} title="Download attached file">
                            <FileText className="w-3.5 h-3.5" /> Attached
                          </Button>
                        )}
                        <Button
                          size="sm"
                          variant="primary"
                          onClick={() => { setShareTarget(row); setDoctorChoice(row.doctor || DOCTORS[0]); }}
                          title="Share this report to a doctor"
                        >
                          <Send className="w-3.5 h-3.5" /> Share to Doctor
                        </Button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>

      {/* Recently shared */}
      <Card title="Recently Shared Reports" subtitle={`${sharedReports.length} shared with doctors`}>
        {sharedReports.length === 0 ? (
          <p className="text-xs text-slate-400">No reports shared yet.</p>
        ) : (
          <ul className="space-y-2">
            {sharedReports.slice(0, 6).map((r) => (
              <li key={r.id} className="flex items-center justify-between gap-3 p-2.5 rounded-xl bg-slate-50 dark:bg-slate-800/50">
                <div className="min-w-0">
                  <p className="text-xs font-semibold text-slate-800 dark:text-slate-200 truncate">
                    {r.testName} Â· {r.patientName}
                  </p>
                  <p className="text-[11px] text-slate-400">
                    → {r.doctorName} Â· {new Date(r.sharedAt).toLocaleString()}
                  </p>
                </div>
                <Badge variant={r.seen ? 'success' : 'info'}>
                  {r.seen ? <><CheckCircle2 className="w-3 h-3" /> Viewed</> : <><Eye className="w-3 h-3" /> Pending</>}
                </Badge>
              </li>
            ))}
          </ul>
        )}
      </Card>

      {/* Upload modal */}
      {uploadTarget && (
        <Modal isOpen onClose={() => setUploadTarget(null)} title="Attach Report" subtitle={uploadTarget.testName}>
          <div className="space-y-3">
            <p className="text-xs text-slate-500">
              Attach an existing PDF or scan for <strong>{uploadTarget.patientName}</strong> Â· {uploadTarget.testName}.
              Maximum 1.5 MB.
            </p>
            {uploadError && (
              <p className="text-xs text-rose-600 dark:text-rose-400 flex items-start gap-1.5">
                <AlertCircle className="w-3.5 h-3.5 shrink-0 mt-0.5" /> {uploadError}
              </p>
            )}
            <input
              type="file"
              accept="application/pdf,image/*"
              onChange={(e) => onUpload(uploadTarget, e.target.files?.[0])}
              className="w-full text-xs file:mr-3 file:rounded-lg file:border-0 file:bg-slate-900 file:px-3 file:py-2 file:text-white dark:file:bg-white dark:file:text-slate-900"
            />
          </div>
        </Modal>
      )}

      {/* Share modal */}
      {shareTarget && (
        <Modal
          isOpen
          onClose={() => setShareTarget(null)}
          title="Share Report to Doctor"
          subtitle={`${shareTarget.testName} Â· ${shareTarget.patientName}`}
        >
          <div className="space-y-4">
            <div className="p-3 rounded-xl bg-slate-50 dark:bg-slate-800/60 border border-slate-200 dark:border-slate-700">
              <p className="text-[11px] uppercase tracking-wider text-slate-400 font-semibold">Report contents</p>
              <p className="text-xs text-slate-700 dark:text-slate-200 mt-1">
                Patient {shareTarget.patientName} ({shareTarget.patientId}) Â· {shareTarget.testName}
              </p>
              <p className="text-[11px] text-slate-400 mt-1">
                {fileRefs.current[shareTarget.key] ? 'Includes the attached PDF.' : 'No file attached - a generated PDF summary will be shared.'}
              </p>
            </div>

            <Select
              label="Select doctor"
              options={DOCTORS}
              placeholder={null}
              value={doctorChoice}
              onChange={(e) => setDoctorChoice(e.target.value)}
            />

            <div className="flex items-center justify-end gap-2">
              <Button variant="ghost" onClick={() => setShareTarget(null)}>Cancel</Button>
              <Button variant="primary" onClick={doShare}>
                <Send className="w-4 h-4" /> Share Report
              </Button>
            </div>
          </div>
        </Modal>
      )}

      {toast && (
        <div className="fixed bottom-6 right-6 z-50 flex items-center gap-2 px-4 py-3 rounded-xl bg-slate-900 text-white text-xs font-semibold shadow-2xl">
          <CheckCircle2 className="w-4 h-4 text-emerald-400" /> {toast}
        </div>
      )}
    </div>
  );
}

export default LabTechnician;